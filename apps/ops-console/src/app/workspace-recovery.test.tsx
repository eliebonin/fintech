import {beforeEach,afterEach,expect,it,vi} from 'vitest';
import {renderToStaticMarkup} from 'react-dom/server';
vi.mock('server-only',()=>({}));
vi.mock('next/navigation',()=>({redirect:(path:string)=>{throw new Error('redirect:'+path);},usePathname:()=>'/instruments',useRouter:()=>({refresh:vi.fn()})}));
const h=vi.hoisted(()=>({context:vi.fn(),workspace:vi.fn()}));
vi.mock('@/lib/tenant-session',()=>({getActiveTenantContext:h.context,getActiveTenantWorkspace:h.workspace}));
import {SessionRequiredError,WorkspaceApiError} from '@/lib/server/workspace-errors';
import Instruments from './instruments/page';
import Operations from './operations/page';
import Strategies from './strategies/page';
import MarketData from './market-data/page';
import Valuation from './valuation/page';
import Trades from './trades/page';
import TenantProfile from './tenant-profile/page';
import TradeConfiguration from './tenant-profile/trade-configuration/page';
import Calendars from './market-data/calendars/page';
import Policies from './market-data/policies/page';
const routes=[['tenant-profile',()=>TenantProfile()],['trade-configuration',()=>TradeConfiguration()],['calendars',()=>Calendars()],['policies',()=>Policies()],['instruments',()=>Instruments()],['operations',()=>Operations()],['strategies',()=>Strategies()],['market-data',()=>MarketData({searchParams:Promise.resolve({})})],['valuation',()=>Valuation()],['trades',()=>Trades({searchParams:Promise.resolve({range:'all'})})]] as const;
beforeEach(()=>{h.context.mockResolvedValue({tenantId:'tenant',userAccountId:'actor',source:'local-session'});h.workspace.mockRejectedValue(new WorkspaceApiError(503));});
afterEach(()=>{vi.clearAllMocks();vi.unstubAllGlobals();});
it.each(routes)('preserves the selected tenant and offers retry when %s workspace fails',async(_name,run)=>{const html=renderToStaticMarkup(await run());expect(html).toContain('selected tenant has been preserved');expect(html).toContain('Try again');expect(html).not.toContain('<form');});
it.each(routes)('explains forbidden workspace access for %s',async(_name,run)=>{h.workspace.mockRejectedValue(new WorkspaceApiError(403));const html=renderToStaticMarkup(await run());expect(html).toContain('access restricted');expect(html).not.toContain('<form');});
it('redirects missing sessions before trying to load a workspace',async()=>{h.context.mockRejectedValue(new SessionRequiredError());await expect(Instruments()).rejects.toThrow('redirect:/select-tenant');expect(h.workspace).not.toHaveBeenCalled();});
it('keeps navigation pending until catalogue content is ready instead of committing a loading screen',async()=>{
  h.workspace.mockResolvedValue({tenantId:'tenant',tenantName:'Tenant',membershipRole:'READ_ONLY',moduleCodes:[]});
  let finish!: (response: Response)=>void;
  vi.stubGlobal('fetch',vi.fn(()=>new Promise<Response>(resolve=>{finish=resolve;})));
  let settled=false;
  const navigation=Instruments().then(page=>{settled=true;return page;});
  await vi.waitFor(()=>expect(finish).toBeTypeOf('function'));
  expect(settled).toBe(false);
  finish(Response.json({data:[],meta:{source:'live-reference-api',total:0}}));
  const page=await navigation;
  expect(page.type).not.toBe(Symbol.for('react.suspense'));
  expect(page.props.initialSource).toBe('LIVE API');
});
it('shows unavailable strategies rather than an empty success list',async()=>{h.workspace.mockResolvedValue({tenantId:'tenant',tenantName:'Tenant',membershipRole:'READ_ONLY',moduleCodes:[]});vi.stubGlobal('fetch',async()=>Response.json({}, {status:503}));const html=renderToStaticMarkup(await Strategies());expect(html).toContain('temporarily unavailable');expect(html).not.toContain('No strategies');});
